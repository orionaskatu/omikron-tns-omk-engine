"""Embed `engine/lang/omk-menu.ini` into the engine as
`engine/src/ui/omktext_data.cpp` (`todo/graphics-menu.md` A2b).

The texts of OMK's own menu rows live in an editable file, but every port has
to carry them - the Vita's VPK, the 3DS romfs, the classic Mac bundle - and
each packages files its own way. Compiled in, they reach every port through
the `src/*/*.cpp` every build globs, and a copy of the file beside the config
still overrides them (`ui/omktext.h`).

    python3 tools/omklang.py           # write the .cpp
    python3 tools/omklang.py --check   # exit 1 when it is stale

The comment lines are dropped; every other line is kept as it is, its bytes
written as octal escapes past ASCII (octal, never `\\x`, which runs on into a
following hex digit). `verify.py: omk lang` fails on a stale copy.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "engine", "lang", "omk-menu.ini")
OUT = os.path.join(ROOT, "engine", "src", "ui", "omktext_data.cpp")


def literal(line):
    out = []
    for b in line.encode("utf-8"):
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '\\n"'


def generate():
    lines = []
    with open(SRC, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            s = line.strip()
            if not s or s.startswith(";") or s.startswith("#"):
                continue
            lines.append(line)
    body = "\n".join("        " + literal(l) for l in lines)
    return ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
            "// GENERATED by tools/omklang.py from engine/lang/omk-menu.ini - do not edit;\n"
            "// edit the .ini and run the tool. `verify.py: omk lang` fails on a stale copy.\n"
            "#include \"ui/omktext.h\"\n\n"
            "namespace omk {\n\n"
            "const char* omkMenuStrings() {\n"
            "    return\n" + body + ";\n"
            "}\n\n"
            "}  // namespace omk\n")


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("stale: %s - run python3 tools/omklang.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("fresh: %s" % os.path.relpath(OUT, ROOT))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
