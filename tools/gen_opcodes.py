r"""Write `engine/src/script/opcodes.h` - the VM's opcode NUMBERS by NAME.

The 153-opcode table lives in `tables/vm_opcodes.json` (lifted from the
executable by `tools/exetables.py`, named in `docs/SCRIPT_VM.md`). The C++
compared raw numbers - `case 118: case 119:`, `op == 61` - so nobody could
grep "where is dialog.start handled" (`todo/code-readability-audit.md`). This
turns every NAMED row into a constant:

    dialog.start  -> op::DialogStart = 61
    jmp_if_true   -> op::JmpIfTrue   = 5
    push.i8       -> op::PushI8      = 7

An unnamed row gets `op::Op<NNN>` so every number has a spelling. The names
are the TABLE's, which is the repo's naming of record; where the code knows a
table name to be misleading it says so at the use.

    python3 tools/gen_opcodes.py           # (re)write the header
    python3 tools/gen_opcodes.py --check   # exit 1 if the header is stale

`verify.py: opcode names` runs the check, so a renamed row cannot leave the
header behind.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "tables", "vm_opcodes.json")
HEADER = os.path.join(ROOT, "engine", "src", "script", "opcodes.h")


def ident(name, op):
    if not name:
        return "Op%03d" % op
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[._]", name) if p)


def render():
    rows = json.load(open(TABLE))["rows"]
    seen = {}
    lines = []
    for r in rows:
        n = ident(r.get("name"), r["op"])
        if n in seen:
            sys.exit("two opcodes spell %s: %d and %d" % (n, seen[n], r["op"]))
        seen[n] = r["op"]
        tail = "  // %s" % r["name"] if r.get("name") else "  // not named in the table"
        lines.append("inline constexpr int %-22s = %3d;%s" % (n, r["op"], tail))
    return (
        "// SPDX-License-Identifier: GPL-3.0-or-later\n"
        "//\n"
        "// script/opcodes.h - the VM's 153 opcodes by NAME. GENERATED by\n"
        "// `tools/gen_opcodes.py` from `tables/vm_opcodes.json`: do not edit, rerun\n"
        "// it (`verify.py: opcode names` fails while this is stale). The names are\n"
        "// the table's - `docs/SCRIPT_VM.md` is where each was established.\n"
        "#pragma once\n\n"
        "namespace omk::op {\n\n" + "\n".join(lines) + "\n\n}  // namespace omk::op\n")


def main(argv):
    text = render()
    if "--check" in argv:
        cur = open(HEADER).read() if os.path.exists(HEADER) else ""
        if cur != text:
            print("engine/src/script/opcodes.h is STALE - run tools/gen_opcodes.py")
            return 1
        print("opcodes.h matches tables/vm_opcodes.json (%d opcodes)" % text.count("inline constexpr"))
        return 0
    with open(HEADER, "w") as f:
        f.write(text)
    print("wrote %s" % HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
